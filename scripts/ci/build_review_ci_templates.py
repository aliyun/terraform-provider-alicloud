#!/usr/bin/env python3
"""Generate self-contained, immutable CI templates (no MR checkout needed)."""
from pathlib import Path
root = Path(__file__).resolve().parent.parent.parent
(root / 'ci/templates').mkdir(parents=True, exist_ok=True)
for kind, label in [('formal', '形式化评审'), ('ai', 'AI评审')]:
    script = (root / 'scripts/ci' / ('review_ci_disabled.py' if kind == 'ai' else 'review_ci.py')).read_text()
    header = '''# Generated by scripts/ci/build_review_ci_templates.py; edit the Python source, then regenerate.
name: ACube LABEL
jobs:
  review:
    name: ACube LABEL
    timeout: 8h
    image: alios-8u
    steps:
      - uses: setup-env
        inputs:
          python-version: '3.9'
      - name: 运行评审并生成报告
        envs:
          ACUBE_REVIEW_KIND: @KIND@
          ACUBE_MR: '${{git.merge_request.id}}'
          ACUBE_HEAD: '${{git.commitId}}'
          ACUBE_CI_RUN: '${{pipeline.inst.id}}'
          ACUBE_PROVIDER_RUN_TOKEN: '${{secrets.ACUBE_PROVIDER_RUN_TOKEN}}'
        run: |
          set +x
          python3 - <<'ACUBE_REVIEW_PY'
'''.replace('LABEL', label).replace('@KIND@', kind)
    if kind == 'ai':
        header = header.replace('timeout: 8h', 'timeout: 5m').replace('运行评审并生成报告', 'AI 评审已关闭，默认通过')
        header = header.replace("          ACUBE_PROVIDER_RUN_TOKEN: '${{secrets.ACUBE_PROVIDER_RUN_TOKEN}}'\n", '')
    body = ''.join(('          ' + line if line else '') + '\n' for line in script.splitlines())
    (root / ('ci/templates/acube-' + kind + '-review.yaml')).write_text(header + body + '          ACUBE_REVIEW_PY\n')

#!/usr/bin/env python3
"""Generate self-contained, immutable CI templates (no MR checkout needed).

Both checks embed the same trusted bridge, review_ci.py; only the review kind and the names differ.
"""
import re
from pathlib import Path
root = Path(__file__).resolve().parent.parent.parent
(root / 'ci/templates').mkdir(parents=True, exist_ok=True)
script = (root / 'scripts/ci/review_ci.py').read_text()
body = ''.join(('          ' + line if line else '') + '\n' for line in script.splitlines())
# Use the same trusted event and project receipt as the repository checks.
basic = (root / '.aoneci/acctest-terraform-basic.yml').read_text()
guard = re.search(r'^  VERIFIED_RELEASE_RETURN: >-\n(?:    [^\n]+\n)+', basic, re.MULTILINE).group()
for kind, label, review in [('formal', '形式化评审', 'formal review'), ('ai', 'AI评审', 'AI review')]:
    header = '''# Generated by scripts/ci/build_review_ci_templates.py; edit the Python source, then regenerate.
name: ACube @LABEL@
envs:
@GUARD@jobs:
  review:
    name: ACube @LABEL@
    timeout: 8h
    image: alios-8u
    steps:
      - name: Record release return exemption
        when: ${{ envs.VERIFIED_RELEASE_RETURN == 'yes' }}
        envs:
          REVIEW_MR: '${{git.merge_request.id}}'
          REVIEW_HEAD: '${{git.commitId}}'
        run: echo "Verified release return MR $REVIEW_MR at $REVIEW_HEAD. Skipped ACube @REVIEW@ by policy."
      - uses: setup-env
        when: ${{ envs.VERIFIED_RELEASE_RETURN != 'yes' }}
        inputs:
          python-version: '3.9'
      - name: 运行评审并生成报告
        when: ${{ envs.VERIFIED_RELEASE_RETURN != 'yes' }}
        envs:
          ACUBE_REVIEW_KIND: @KIND@
          ACUBE_MR: '${{git.merge_request.id}}'
          ACUBE_HEAD: '${{git.commitId}}'
          ACUBE_CI_RUN: '${{pipeline.inst.id}}'
          ACUBE_PROVIDER_RUN_TOKEN: '${{secrets.ACUBE_PROVIDER_RUN_TOKEN}}'
        run: |
          set +x
          python3 - <<'ACUBE_REVIEW_PY'
'''
    for placeholder, value in (('@LABEL@', label), ('@GUARD@', guard), ('@REVIEW@', review), ('@KIND@', kind)):
        header = header.replace(placeholder, value)
    (root / ('ci/templates/acube-' + kind + '-review.yaml')).write_text(header + body + '          ACUBE_REVIEW_PY\n')

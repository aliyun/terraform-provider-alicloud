func (r *virtualResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan virtualResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	client := r.Client()
	clusterId := plan.ClusterId.ValueString()
	if clusterId == "" {
		clusterId = client.RegionId
	}

	body := map[string]interface{}{}
	if !plan.VirtualResourceName.IsNull() && plan.VirtualResourceName.ValueString() != "" {
		body["VirtualResourceName"] = plan.VirtualResourceName.ValueString()
	}
	if !plan.DisableSpotProtectionPeriod.IsNull() {
		body["DisableSpotProtectionPeriod"] = plan.DisableSpotProtectionPeriod.ValueBool()
	}
	if items := buildResourcesBody(plan.Resources); len(items) > 0 {
		body["Resources"] = items
	}

	action := "/api/v2/virtualresources"
	query := map[string]*string{"ClusterId": stringPointer(clusterId)}
	response, err := client.RoaPost("EAS", "2021-07-01", action, query, nil, body, true)
	if err != nil {
		resp.Diagnostics.AddError(
			fmt.Sprintf("Creating %s: calling CreateVirtualResource", virtualResourceTypeName),
			errs.WrapErrorf(err, "Creating %s: calling CreateVirtualResource", virtualResourceTypeName).Error(),
		)
		return
	}

	virtualResourceId, _ := response["VirtualResourceId"].(string)
	if virtualResourceId == "" {
		// Some EAS responses surface the generated id under the name key; accept
		// that fallback before failing so a slightly different shape still works.
		if name, _ := response["VirtualResourceName"].(string); name != "" {
			virtualResourceId = name
		}
	}
	if virtualResourceId == "" {
		resp.Diagnostics.AddError(
			fmt.Sprintf("Creating %s: calling CreateVirtualResource", virtualResourceTypeName),
			fmt.Sprintf("the response carried no VirtualResourceId: %v", response),
		)
		return
	}

	plan.Id = types.StringValue(fmt.Sprintf("%s:%s", clusterId, virtualResourceId))
	plan.VirtualResourceId = types.StringValue(virtualResourceId)
	plan.ClusterId = types.StringValue(clusterId)

	object, err := describeVirtualResource(client, clusterId, virtualResourceId)
	if err != nil {
		resp.Diagnostics.AddError(
			fmt.Sprintf("Reading %s: calling DescribeVirtualResource", virtualResourceTypeName),
			errs.WrapErrorf(err, "Reading %s: calling DescribeVirtualResource", virtualResourceTypeName).Error(),
		)
		return
	}
	if object == nil {
		resp.Diagnostics.AddError(
			fmt.Sprintf("Creating %s: calling CreateVirtualResource", virtualResourceTypeName),
			fmt.Sprintf("the virtual resource %s is not visible via DescribeVirtualResource right after creation", virtualResourceId),
		)
		return
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, virtualResourceState(ctx, object, plan.Id.ValueString()))...)
}

func (r *virtualResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state virtualResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	clusterId, virtualResourceId, ok := parseVirtualResourceId(state.Id.ValueString())
	if !ok {
		resp.Diagnostics.AddError(
			fmt.Sprintf("Reading %s: parsing resource id", virtualResourceTypeName),
			fmt.Sprintf("the resource id %q is not in the form `<cluster_id>:<virtual_resource_id>`", state.Id.ValueString()),
		)
		return
	}

	object, err := describeVirtualResource(r.Client(), clusterId, virtualResourceId)
	if err != nil {
		resp.Diagnostics.AddError(
			fmt.Sprintf("Reading %s: calling DescribeVirtualResource", virtualResourceTypeName),
			errs.WrapErrorf(err, "Reading %s: calling DescribeVirtualResource", virtualResourceTypeName).Error(),
		)
		return
	}
	if object == nil {
		resp.State.RemoveResource(ctx)
		return
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, virtualResourceState(ctx, object, state.Id.ValueString()))...)
}

func (r *virtualResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan virtualResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	client := r.Client()
	clusterId, virtualResourceId, ok := parseVirtualResourceId(plan.Id.ValueString())
	if !ok {
		resp.Diagnostics.AddError(
			fmt.Sprintf("Updating %s: parsing resource id", virtualResourceTypeName),
			fmt.Sprintf("the resource id %q is not in the form `<cluster_id>:<virtual_resource_id>`", plan.Id.ValueString()),
		)
		return
	}

	body := map[string]interface{}{}
	if !plan.VirtualResourceName.IsNull() && plan.VirtualResourceName.ValueString() != "" {
		body["VirtualResourceName"] = plan.VirtualResourceName.ValueString()
	}
	if !plan.DisableSpotProtectionPeriod.IsNull() {
		body["DisableSpotProtectionPeriod"] = plan.DisableSpotProtectionPeriod.ValueBool()
	}
	if items := buildResourcesBody(plan.Resources); len(items) > 0 {
		body["Resources"] = items
	}

	action := fmt.Sprintf("/api/v2/virtualresources/%s/%s", clusterId, virtualResourceId)
	query := map[string]*string{"ClusterId": stringPointer(clusterId)}
	if _, err := client.RoaPut("EAS", "2021-07-01", action, query, nil, body, true); err != nil {
		resp.Diagnostics.AddError(
			fmt.Sprintf("Updating %s: calling UpdateVirtualResource", virtualResourceTypeName),
			errs.WrapErrorf(err, "Updating %s: calling UpdateVirtualResource", virtualResourceTypeName).Error(),
		)
		return
	}

	object, err := describeVirtualResource(client, clusterId, virtualResourceId)
	if err != nil {
		resp.Diagnostics.AddError(
			fmt.Sprintf("Reading %s: calling DescribeVirtualResource", virtualResourceTypeName),
			errs.WrapErrorf(err, "Reading %s: calling DescribeVirtualResource", virtualResourceTypeName).Error(),
		)
		return
	}
	if object == nil {
		resp.State.RemoveResource(ctx)
		return
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, virtualResourceState(ctx, object, plan.Id.ValueString()))...)
}

func (r *virtualResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state virtualResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	clusterId, virtualResourceId, ok := parseVirtualResourceId(state.Id.ValueString())
	if !ok {
		resp.Diagnostics.AddError(
			fmt.Sprintf("Deleting %s: parsing resource id", virtualResourceTypeName),
			fmt.Sprintf("the resource id %q is not in the form `<cluster_id>:<virtual_resource_id>`", state.Id.ValueString()),
		)
		return
	}

	action := fmt.Sprintf("/api/v2/virtualresources/%s/%s", clusterId, virtualResourceId)
	query := map[string]*string{"ClusterId": stringPointer(clusterId)}
	_, err := r.Client().RoaDelete("EAS", "2021-07-01", action, query, nil, nil, true)
	if err != nil && !isVirtualResourceNotExist(err) {
		resp.Diagnostics.AddError(
			fmt.Sprintf("Deleting %s: calling DeleteVirtualResource", virtualResourceTypeName),
			errs.WrapErrorf(err, "Deleting %s: calling DeleteVirtualResource", virtualResourceTypeName).Error(),
		)
		return
	}
}


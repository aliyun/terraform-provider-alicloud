// lintignore: AT001
func TestAccAliCloudWafProtectionModule_basic0(t *testing.T) {
	var v map[string]interface{}
	acctest.CheckoutSupportedRegions(t, true, connectivity.WAFSupportRegions)
	resourceId := "alicloud_waf_protection_module.default"
	ra := acctest.ResourceAttrInit(resourceId, AlicloudWAFProtectionModuleMap0)
	rc := acctest.ResourceCheckInitWithDescribeMethod(resourceId, &v, func() interface{} {
		return waf.NewService(acctest.Provider.Meta().(*connectivity.AliyunClient))
	}, "DescribeWafProtectionModule")
	rac := acctest.ResourceAttrCheckInit(rc, ra)
	testAccCheck := rac.ResourceAttrMapUpdateSet()
	rand := tfacctest.RandIntRange(10000, 99999)
	name := fmt.Sprintf("tf-testacc%swafprotectionmodule%d", acctest.DefaultRegionToTest, rand)
	testAccConfig := acctest.ResourceTestAccConfig(resourceId, name, AlicloudWAFProtectionModuleBasicDependence0)
	resource.Test(t, resource.TestCase{
		PreCheck: func() {
			acctest.PreCheck(t)
		},
		ProtoV5ProviderFactories: acctest.ProtoV5ProviderFactories(),
		Steps: []resource.TestStep{
			{
				Config: testAccConfig(map[string]interface{}{
					"instance_id":  "${data.alicloud_waf_instances.default.ids.0}",
					"domain":       "${alicloud_waf_domain.default.domain_name}",
					"defense_type": "ac_cc",
					"mode":         "0",
					"status":       "0",
				}),
				Check: resource.ComposeTestCheckFunc(
					testAccCheck(map[string]string{
						"domain":       acctest.CHECKSET,
						"instance_id":  acctest.CHECKSET,
						"defense_type": "ac_cc",
						"mode":         "0",
						"status":       "0",
					}),
				),
			},
			{
				Config: testAccConfig(map[string]interface{}{
					"mode": "1",
				}),
				Check: resource.ComposeTestCheckFunc(
					testAccCheck(map[string]string{
						"mode": "1",
					}),
				),
			},
			{
				Config: testAccConfig(map[string]interface{}{
					"status": "1",
				}),
				Check: resource.ComposeTestCheckFunc(
					testAccCheck(map[string]string{
						"status": "1",
					}),
				),
			},
			{
				Config: testAccConfig(map[string]interface{}{
					"mode":   "0",
					"status": "0",
				}),
				Check: resource.ComposeTestCheckFunc(
					testAccCheck(map[string]string{
						"mode":   "0",
						"status": "0",
					}),
				),
			},
			{
				ResourceName:      resourceId,
				ImportState:       true,
				ImportStateVerify: true,
			},
		},
	})
}


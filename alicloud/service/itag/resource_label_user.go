// getItagLabelUser queries GetUser for a single label user and returns the
// SimpleUser object, or nil when the user no longer exists.
func getItagLabelUser(client *connectivity.AliyunClient, tenantId, userId string) (map[string]interface{}, error) {
	action := fmt.Sprintf("/openapi/api/v1/tenants/%s/users/%s", tenantId, userId)
	response, err := client.RoaGet("Openitag", "2022-06-16", action, map[string]*string{}, nil, nil)
	if err != nil {
		if errs.NotFoundError(err) {
			return nil, nil
		}
		return nil, err
	}
	user, _ := response["User"].(map[string]interface{})
	if user == nil {
		return nil, fmt.Errorf("the GetUser response carried no User object: %v", response)
	}
	return user, nil
}

// itagLabelUserState maps a SimpleUser object onto the resource model. Empty
// values become null so absent API fields read back as unset, not "".
func itagLabelUserState(user map[string]interface{}) itagLabelUserModel {
	str := func(key string) types.String {
		if s := scalarString(user[key]); s != "" {
			return types.StringValue(s)
		}
		return types.StringNull()
	}
	return itagLabelUserModel{
		AccountNo:   str("AccountNo"),
		AccountType: str("AccountType"),
		Role:        str("Role"),
		UserName:    str("UserName"),
		UserId:      str("UserId"),
	}
}

// parseItagLabelUserId splits a composite id "<tenant_id>:<user_id>" into its
// parts. The split is on the first colon so a tenant id containing no colon is
// handled; user ids are numeric and never contain one.
func parseItagLabelUserId(id string) (string, string, bool) {
	parts := strings.SplitN(id, ":", 2)
	if len(parts) != 2 || parts[0] == "" || parts[1] == "" {
		return "", "", false
	}
	return parts[0], parts[1], true
}

// scalarString coerces a response value to a string. JSON numbers land as
// float64 in the ROA helper's map[string]interface{}; UserId is int64 on the
// wire, so the numeric branch keeps it intact for ids below 2^53.
func scalarString(v interface{}) string {
	switch x := v.(type) {
	case nil:
		return ""
	case string:
		return x
	case float64:
		return strconv.FormatInt(int64(x), 10)
	case int64:
		return strconv.FormatInt(x, 10)
	case int:
		return strconv.Itoa(x)
	default:
		return fmt.Sprintf("%v", v)
	}
}

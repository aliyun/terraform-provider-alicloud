func (r *itagLabelUserResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan itagLabelUserModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	tenantId := plan.TenantId.ValueString()
	action := fmt.Sprintf("/openapi/api/v1/tenants/%s/users", tenantId)
	body := map[string]interface{}{
		"AccountNo":   plan.AccountNo.ValueString(),
		"AccountType": plan.AccountType.ValueString(),
		"Role":        plan.Role.ValueString(),
	}
	if !plan.UserName.IsNull() {
		body["UserName"] = plan.UserName.ValueString()
	}

	response, err := r.Client().RoaPost("Openitag", "2022-06-16", action, map[string]*string{}, nil, body, true)
	if err != nil {
		resp.Diagnostics.AddError(
			fmt.Sprintf("Creating %s: calling CreateUser", itagLabelUserTypeName),
			errs.WrapErrorf(err, "Creating %s: calling CreateUser", itagLabelUserTypeName).Error(),
		)
		return
	}

	userId := scalarString(response["UserId"])
	if userId == "" {
		resp.Diagnostics.AddError(
			fmt.Sprintf("Creating %s: calling CreateUser", itagLabelUserTypeName),
			fmt.Sprintf("The CreateUser response carried no UserId: %v", response),
		)
		return
	}

	object, err := getItagLabelUser(r.Client(), tenantId, userId)
	if err != nil {
		resp.Diagnostics.AddError(
			fmt.Sprintf("Reading %s: calling GetUser", itagLabelUserTypeName),
			errs.WrapErrorf(err, "Reading %s: calling GetUser", itagLabelUserTypeName).Error(),
		)
		return
	}
	if object == nil {
		resp.Diagnostics.AddError(
			fmt.Sprintf("Creating %s: calling CreateUser", itagLabelUserTypeName),
			fmt.Sprintf("The label user %s is not visible via GetUser right after creation", userId),
		)
		return
	}

	state := itagLabelUserState(object)
	state.Id = types.StringValue(fmt.Sprintf("%s:%s", tenantId, userId))
	state.TenantId = plan.TenantId
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *itagLabelUserResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state itagLabelUserModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	tenantId, userId, ok := parseItagLabelUserId(state.Id.ValueString())
	if !ok {
		resp.Diagnostics.AddError(
			fmt.Sprintf("Reading %s: parsing id", itagLabelUserTypeName),
			fmt.Sprintf("The id %q is not in the expected `<tenant_id>:<user_id>` format", state.Id.ValueString()),
		)
		return
	}

	object, err := getItagLabelUser(r.Client(), tenantId, userId)
	if err != nil {
		resp.Diagnostics.AddError(
			fmt.Sprintf("Reading %s: calling GetUser", itagLabelUserTypeName),
			errs.WrapErrorf(err, "Reading %s: calling GetUser", itagLabelUserTypeName).Error(),
		)
		return
	}
	if object == nil {
		resp.State.RemoveResource(ctx)
		return
	}

	newState := itagLabelUserState(object)
	newState.Id = state.Id
	newState.TenantId = types.StringValue(tenantId)
	resp.Diagnostics.Append(resp.State.Set(ctx, &newState)...)
}

func (r *itagLabelUserResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan, state itagLabelUserModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	tenantId := state.TenantId.ValueString()
	userId := state.UserId.ValueString()
	if userId == "" {
		if _, u, ok := parseItagLabelUserId(state.Id.ValueString()); ok {
			userId = u
		}
	}

	// UpdateUser requires both Role and UserName in the body. When UserName is
	// unset in the config, the prior state value is preserved so the API always
	// receives a non-empty name.
	userName := plan.UserName.ValueString()
	if plan.UserName.IsNull() || userName == "" {
		userName = state.UserName.ValueString()
	}

	action := fmt.Sprintf("/openapi/api/v1/tenants/%s/users/%s", tenantId, userId)
	body := map[string]interface{}{
		"Role":     plan.Role.ValueString(),
		"UserName": userName,
	}
	if _, err := r.Client().RoaPut("Openitag", "2022-06-16", action, map[string]*string{}, nil, body, true); err != nil {
		resp.Diagnostics.AddError(
			fmt.Sprintf("Updating %s: calling UpdateUser", itagLabelUserTypeName),
			errs.WrapErrorf(err, "Updating %s: calling UpdateUser", itagLabelUserTypeName).Error(),
		)
		return
	}

	object, err := getItagLabelUser(r.Client(), tenantId, userId)
	if err != nil {
		resp.Diagnostics.AddError(
			fmt.Sprintf("Reading %s: calling GetUser", itagLabelUserTypeName),
			errs.WrapErrorf(err, "Reading %s: calling GetUser", itagLabelUserTypeName).Error(),
		)
		return
	}
	if object == nil {
		resp.State.RemoveResource(ctx)
		return
	}

	newState := itagLabelUserState(object)
	newState.Id = state.Id
	newState.TenantId = types.StringValue(tenantId)
	resp.Diagnostics.Append(resp.State.Set(ctx, &newState)...)
}


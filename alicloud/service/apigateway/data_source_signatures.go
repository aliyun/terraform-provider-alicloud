const signaturesTypeName = "alicloud_api_gateway_signatures"

var (
	_ datasource.DataSource              = &signaturesDataSource{}
	_ datasource.DataSourceWithConfigure = &signaturesDataSource{}
)

// signatureObjectType is the Framework object type for one entry of the signatures
// list. It mirrors the NestedAttributeObject in Schema so a []signatureItem slice can
// be converted into a list value by ListValueFrom via struct-tag reflection.
var signatureObjectType = types.ObjectType{
	AttrTypes: map[string]attr.Type{
		"id":               types.StringType,
		"signature_name":   types.StringType,
		"signature_key":    types.StringType,
		"signature_secret": types.StringType,
		"created_time":     types.StringType,
		"modified_time":    types.StringType,
		"region_id":        types.StringType,
	},
}

func NewSignaturesDataSource() datasource.DataSource {
	return &signaturesDataSource{}
}

type signaturesDataSource struct {
	fwadapt.DataSourceBase
}

type signaturesDataSourceModel struct {
	Id         types.String `tfsdk:"id"`
	NameRegex  types.String `tfsdk:"name_regex"`
	Ids        types.List   `tfsdk:"ids"`
	OutputFile types.String `tfsdk:"output_file"`
	Names      types.List   `tfsdk:"names"`
	Signatures types.List   `tfsdk:"signatures"`
}

type signatureItem struct {
	Id              types.String `tfsdk:"id"`
	SignatureName   types.String `tfsdk:"signature_name"`
	SignatureKey    types.String `tfsdk:"signature_key"`
	SignatureSecret types.String `tfsdk:"signature_secret"`
	CreatedTime     types.String `tfsdk:"created_time"`
	ModifiedTime    types.String `tfsdk:"modified_time"`
	RegionId        types.String `tfsdk:"region_id"`
}

func (d *signaturesDataSource) Metadata(ctx context.Context, req datasource.MetadataRequest, resp *datasource.MetadataResponse) {
	resp.TypeName = signaturesTypeName
}

func (d *signaturesDataSource) Schema(ctx context.Context, req datasource.SchemaRequest, resp *datasource.SchemaResponse) {
	resp.Schema = schema.Schema{
		Description: "This data source provides the API Gateway signatures of the current Alibaba Cloud user.",
		Attributes: map[string]schema.Attribute{
			"id": schema.StringAttribute{
				Computed:    true,
				Description: "The data source ID, set to the number of matched signatures.",
			},
			"name_regex": schema.StringAttribute{
				Optional:    true,
				Description: "A regex string to filter signatures by name.",
			},
			"ids": schema.ListAttribute{
				ElementType: types.StringType,
				Optional:    true,
				Computed:    true,
				Description: "A list of signature IDs. Used to filter the result and exported as the matched IDs.",
			},
			"output_file": schema.StringAttribute{
				Optional:    true,
				Description: "File name where to save data source results (after running terraform plan).",
			},
			"names": schema.ListAttribute{
				ElementType: types.StringType,
				Computed:    true,
				Description: "A list of signature names.",
			},
			"signatures": schema.ListNestedAttribute{
				Computed: true,
				NestedObject: schema.NestedAttributeObject{
					Attributes: map[string]schema.Attribute{
						"id": schema.StringAttribute{
							Computed:    true,
							Description: "The ID of the signature, generated by the system and globally unique.",
						},
						"signature_name": schema.StringAttribute{
							Computed:    true,
							Description: "The name of the signature.",
						},
						"signature_key": schema.StringAttribute{
							Computed:    true,
							Description: "The key of the signature.",
						},
						"signature_secret": schema.StringAttribute{
							Computed:    true,
							Description: "The secret of the signature.",
						},
						"created_time": schema.StringAttribute{
							Computed:    true,
							Description: "The creation time of the signature.",
						},
						"modified_time": schema.StringAttribute{
							Computed:    true,
							Description: "The last modification time of the signature.",
						},
						"region_id": schema.StringAttribute{
							Computed:    true,
							Description: "The region ID of the signature.",
						},
					},
				},
				Description: "A list of signatures. Each element contains the following attributes.",
			},
		},
	}
}

func (d *signaturesDataSource) Read(ctx context.Context, req datasource.ReadRequest, resp *datasource.ReadResponse) {
	var config signaturesDataSourceModel
	resp.Diagnostics.Append(req.Config.Get(ctx, &config)...)
	if resp.Diagnostics.HasError() {
		return
	}

	client := d.Client()

	request := cloudapi.CreateDescribeSignaturesRequest()
	request.RegionId = client.RegionId
	request.PageSize = requests.NewInteger(pageSizeLarge)
	request.PageNumber = requests.NewInteger(1)

	var all []cloudapi.SignatureInfo
	for {
		raw, err := client.WithCloudApiClient(func(cloudApiClient *cloudapi.Client) (interface{}, error) {
			return cloudApiClient.DescribeSignatures(request)
		})
		if err != nil {
			resp.Diagnostics.AddError(
				fmt.Sprintf("Reading %s: calling DescribeSignatures", signaturesTypeName),
				errs.WrapErrorf(err, errs.DataDefaultErrorMsg, signaturesTypeName, request.GetActionName(), errs.AlibabaCloudSdkGoERROR).Error(),
			)
			return
		}
		response, _ := raw.(*cloudapi.DescribeSignaturesResponse)

		all = append(all, response.SignatureInfos.SignatureInfo...)

		if len(all) >= response.TotalCount {
			break
		}
		page, err := nextPageNumber(request.PageNumber)
		if err != nil {
			resp.Diagnostics.AddError(
				fmt.Sprintf("Reading %s: paging DescribeSignatures", signaturesTypeName),
				errs.WrapError(err).Error(),
			)
			return
		}
		request.PageNumber = page
	}

	var nameRegex *regexp.Regexp
	if !config.NameRegex.IsNull() && config.NameRegex.ValueString() != "" {
		r, err := regexp.Compile(config.NameRegex.ValueString())
		if err != nil {
			resp.Diagnostics.AddError(
				fmt.Sprintf("Reading %s: compiling name_regex", signaturesTypeName),
				errs.WrapError(err).Error(),
			)
			return
		}
		nameRegex = r
	}

	var filterIds []string
	if !config.Ids.IsNull() {
		resp.Diagnostics.Append(config.Ids.ElementsAs(ctx, &filterIds, false)...)
		if resp.Diagnostics.HasError() {
			return
		}
	}

	items := make([]signatureItem, 0)
	// outputRows mirrors items with plain strings so json.MarshalIndent in writeToFile
	// produces the attribute values, not the tfsdk types.String envelope.
	outputRows := make([]map[string]string, 0)
	for _, sig := range all {
		if nameRegex != nil && !nameRegex.MatchString(sig.SignatureName) {
			continue
		}
		if len(filterIds) > 0 {
			match := false
			for _, id := range filterIds {
				if sig.SignatureId == id {
					match = true
					break
				}
			}
			if !match {
				continue
			}
		}
		items = append(items, signatureItem{
			Id:              stringOrNull(sig.SignatureId),
			SignatureName:   stringOrNull(sig.SignatureName),
			SignatureKey:    stringOrNull(sig.SignatureKey),
			SignatureSecret: stringOrNull(sig.SignatureSecret),
			CreatedTime:     stringOrNull(sig.CreatedTime),
			ModifiedTime:    stringOrNull(sig.ModifiedTime),
			RegionId:        stringOrNull(sig.RegionId),
		})
		outputRows = append(outputRows, map[string]string{
			"id":               sig.SignatureId,
			"signature_name":   sig.SignatureName,
			"signature_key":    sig.SignatureKey,
			"signature_secret": sig.SignatureSecret,
			"created_time":     sig.CreatedTime,
			"modified_time":    sig.ModifiedTime,
			"region_id":        sig.RegionId,
		})
	}

	nameList := make([]string, 0, len(items))
	idList := make([]string, 0, len(items))
	for _, it := range items {
		nameList = append(nameList, it.SignatureName.ValueString())
		idList = append(idList, it.Id.ValueString())
	}

	idsList, diags := types.ListValueFrom(ctx, types.StringType, idList)
	resp.Diagnostics.Append(diags...)
	namesList, diags := types.ListValueFrom(ctx, types.StringType, nameList)
	resp.Diagnostics.Append(diags...)
	signaturesList, diags := types.ListValueFrom(ctx, signatureObjectType, items)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	state := signaturesDataSourceModel{
		Id:         types.StringValue(fmt.Sprintf("%d", len(items))),
		NameRegex:  config.NameRegex,
		OutputFile: config.OutputFile,
		Ids:        idsList,
		Names:      namesList,
		Signatures: signaturesList,
	}

	if !config.OutputFile.IsNull() && config.OutputFile.ValueString() != "" {
		if err := writeToFile(config.OutputFile.ValueString(), outputRows); err != nil {
			resp.Diagnostics.AddError(
				fmt.Sprintf("Reading %s: writing output_file", signaturesTypeName),
				errs.WrapError(err).Error(),
			)
			return
		}
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

// stringOrNull returns a String value, or null for an empty string, so computed
// attributes the API omits read back as absent rather than "".
func stringOrNull(v string) types.String {
	if v == "" {
		return types.StringNull()
	}
	return types.StringValue(v)
}
